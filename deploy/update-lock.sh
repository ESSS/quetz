#!/usr/bin/env bash
# Re-solves the Quetz env from the repo's environment.yml (the newest conda-forge packages
# that fit its constraints) and rewrites deploy/quetz-linux-64.lock, the lock the
# image is built from. Then: review the diff, `docker compose up -d --build quetz`, test, commit.
#
#   deploy/update-lock.sh [output-file]
#
# Needs only Docker; the solve runs in a throwaway micromamba container.
set -euo pipefail

DEPLOY_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
LOCK="$DEPLOY_DIR/quetz-linux-64.lock"
OUT=${1:-$LOCK}
MICROMAMBA_IMAGE=mambaorg/micromamba:2.0.5@sha256:8d0d4cad074afe3ac93b58dce88bd2659153d3fa6de3a6968f501710e8d3c832

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

echo "Solving $(dirname "$DEPLOY_DIR")/environment.yml for linux-64..." >&2
# repo.mamba.pm (the channel in environment.yml) only redirects; solve against conda-forge.
docker run --rm --platform linux/amd64 \
    -v "$(dirname "$DEPLOY_DIR")/environment.yml:/tmp/environment.yml:ro" \
    "$MICROMAMBA_IMAGE" bash -c '
        set -euo pipefail
        sed "s#https://repo.mamba.pm/conda-forge#conda-forge#" /tmp/environment.yml > /tmp/env.yml
        micromamba create -y -q -p /tmp/env -f /tmp/env.yml >/dev/null
        micromamba env export -p /tmp/env --explicit --md5
    ' | grep '^https://' > "$tmp"

[[ -s "$tmp" ]] || { echo "error: the solve returned no packages" >&2; exit 1; }

{
    echo "# Lock file of the Quetz runtime env for deploy/Dockerfile (linux-64), installed with \`micromamba create -f\`."
    echo "# Generated by deploy/update-lock.sh from environment.yml on $(date -u +%F)."
    echo "# platform: linux-64"
    echo "@EXPLICIT"
    cat "$tmp"
} > "$OUT"

names() { grep '^https://' "$1" | sed 's#.*/##; s#\.conda\#.*##; s#\.tar\.bz2\#.*##' | sort; }
echo "Wrote $OUT: $(grep -c '^https://' "$OUT") packages." >&2
if [[ -f "$LOCK" && "$OUT" != "$LOCK" || -n "$(git -C "$DEPLOY_DIR" diff --name-only -- "$LOCK" 2>/dev/null)" ]]; then
    base=$LOCK
    [[ "$OUT" == "$LOCK" ]] && base=<(git -C "$DEPLOY_DIR" show "HEAD:deploy/$(basename "$LOCK")")
    echo "Changes (- old, + new):" >&2
    diff <(names "$base") <(names "$OUT") | grep '^[<>]' | sed 's/^</-/; s/^>/+/' >&2 || echo "  none" >&2
fi
